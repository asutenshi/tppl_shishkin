; Среднее арифметическое разностей x[i] - y[i] для двух строк чисел из файла.
;
; Ключевая идея: сумма разностей = (сумма x) - (сумма y), поэтому массивы
; хранить не нужно: достаточно пройти по каждой строке, посчитав в ней
; сумму и количество чисел. Если количества разные, файл испорчен.
;
; Файл читаем в цикле до конца (read вернул 0). Буфер под файл растёт через
; системный вызов brk (12): каждый раз просим у ядра ещё CHUNK байт «кучи»
; сразу за уже выделенными.
;
; Формат вывода:  <имя_файла>: <среднее>   или   <имя_файла>: файл испорчен
;
; Кто в каком регистре живёт в _start (они переживают syscall):
;   rbx = сначала fd файла, потом сумма x, потом сумма разностей, потом ответ
;   rbp = сколько чисел в первой строке
;   r12 = адрес начала буфера с содержимым файла
;   r13 = сколько байт файла прочитано
;   r14 = адрес имени файла (argv[1]),  r15 = длина имени

CHUNK equ 65536                     ; на сколько байт расширяем буфер за один шаг (64 КБ)

section .data                       ; данные, которые лежат в памяти с самого старта
    sep         db ": "             ; разделитель между именем файла и результатом
    sep_len     equ $ - sep         ; его длина: текущий адрес минус начало строки
    bad_msg     db "файл испорчен", 10   ; сообщение об ошибке + перевод строки (10 = \n)
    bad_msg_len equ $ - bad_msg     ; длина в байтах (русские буквы занимают по 2 байта)
    usage       db "usage: ./average <file>", 10   ; подсказка, если аргументы неверные
    usage_len   equ $ - usage       ; длина подсказки
    nl          db 10               ; одиночный перевод строки

section .bss                        ; память, заполненная нулями (в файле программы не хранится)
    numbuf     resb 24              ; буфер под текст числа: до 20 цифр int64 + знак '-'
    numbuf_end equ numbuf + 24      ; адрес сразу за буфером: цифры пишем справа налево

section .text                       ; сам код
    global _start                   ; делаем _start видимой для линковщика: отсюда старт

; ---------------------------------------------------------------------------
; write_out: пишет в stdout rdx байт начиная с адреса rsi
write_out:
    mov rax, 1                      ; номер системного вызова write
    mov rdi, 1                      ; куда писать: дескриптор 1 = stdout (экран)
    syscall                         ; зовём ядро; rsi (адрес) и rdx (длина) уже заданы звонящим
    ret                             ; возвращаемся туда, откуда сделали call

; ---------------------------------------------------------------------------
; print_int: печатает число со знаком (без перевода строки). rax = число
; (та же подпрограмма, что в уроке 04)
print_int:
    mov r8, 0                       ; r8 = флаг «число отрицательное», пока 0
    test rax, rax                   ; проверяем знак числа (выставляет флаги по rax)
    jns .abs_done                   ; число >= 0: модуль брать не нужно, пропускаем
    neg rax                         ; число отрицательное: делаем его положительным
    mov r8, 1                       ; и запоминаем, что минус нужно дописать потом
.abs_done:
    mov rsi, numbuf_end             ; rsi = куда писать следующий символ (идём влево от конца)
    mov rcx, 10                     ; делитель: система счисления 10
.digit_loop:
    xor rdx, rdx                    ; обнуляем rdx: div делит пару rdx:rax, старшая часть = 0
    div rcx                         ; rax = rax / 10 (частное), rdx = остаток = последняя цифра
    add dl, '0'                     ; цифру 0..9 превращаем в символ '0'..'9' (код '0' = 48)
    dec rsi                         ; сдвигаемся на байт влево в буфере
    mov [rsi], dl                   ; кладём символ-цифру в буфер
    test rax, rax                   ; частное уже 0? тогда цифры кончились
    jnz .digit_loop                 ; нет: берём следующую цифру
    test r8, r8                     ; число было отрицательным?
    jz .print                       ; нет: сразу печатать
    dec rsi                         ; да: освобождаем ещё один байт слева
    mov byte [rsi], '-'             ; и пишем в него минус
.print:
    mov rdx, numbuf_end             ; длина текста = конец буфера...
    sub rdx, rsi                    ; ...минус начало текста (rsi)
    call write_out                  ; печатаем rdx байт с адреса rsi
    ret                             ; готово

; ---------------------------------------------------------------------------
; skip_ws: пропускает пробелы, табы и '\r' (но не '\n': это конец строки)
;   вход: rsi = текущая позиция, rdi = конец данных
;   выход: rsi сдвинут на первый непробельный символ (или равен rdi)
;   портит: r10
skip_ws:
    cmp rsi, rdi                    ; мы уже дошли до конца данных?
    jae .done                       ; да (rsi >= rdi, беззнаково): пропускать нечего
    mov r10b, [rsi]                 ; берём текущий символ (r10b = младший байт r10)
    cmp r10b, ' '                   ; это пробел?
    je  .skip                       ; да: съедаем
    cmp r10b, 9                     ; это табуляция (код 9)?
    je  .skip                       ; да: съедаем
    cmp r10b, 13                    ; это '\r' (код 13, в файлах с Windows-переводами строк)?
    jne .done                       ; не пробельный символ: останавливаемся
.skip:
    inc rsi                         ; переходим к следующему символу
    jmp skip_ws                     ; и проверяем его так же (цикл)
.done:
    ret                             ; rsi стоит на нужном месте

; ---------------------------------------------------------------------------
; parse_line: разбирает одну строку вида  "5, -3,2 ,6\n"
;   вход:  rsi = начало строки, rdi = конец данных
;   выход: rax = сумма чисел, rcx = сколько чисел, rsi = позиция после '\n'
;          CF = 1, если строка некорректна (иначе CF = 0)
;   портит: rdx, r8, r9, r10
parse_line:
    xor rax, rax                    ; rax = сумма чисел, пока 0
    xor rcx, rcx                    ; rcx = сколько чисел встретили, пока 0
.next_number:                       ; сюда приходим и в начале строки, и после каждой запятой
    call skip_ws                    ; пропускаем пробелы перед числом
    cmp rsi, rdi                    ; данные кончились?
    jae .error                      ; ждали число, а данные кончились: ошибка
    xor r8, r8                      ; r8 = 1, если число отрицательное; пока 0 (после jae: xor портит флаги)
    cmp byte [rsi], '-'             ; первый символ минус?
    jne .digits                     ; нет: сразу разбираем цифры
    mov r8, 1                       ; да: запоминаем, что число отрицательное
    inc rsi                         ; съели минус
.digits:
    xor rdx, rdx                    ; rdx = накопленное значение числа, пока 0
    xor r9, r9                      ; r9 = сколько цифр прочитали, пока 0
.digit_loop:
    cmp rsi, rdi                    ; данные кончились?
    jae .digits_done                ; да: число закончилось
    movzx r10, byte [rsi]           ; берём символ, расширяя нулями до 64 бит
    sub r10, '0'                    ; код символа -> цифра (для символов меньше '0' выйдет огромное число)
    cmp r10, 9                      ; цифра в пределах 0..9?
    ja  .digits_done                ; нет (беззнаково выше 9): это не цифра, число закончилось
    imul rdx, rdx, 10               ; значение = значение * 10 (сдвигаем разряды влево)
    add rdx, r10                    ; значение += новая цифра
    inc rsi                         ; идём к следующему символу
    inc r9                          ; считаем прочитанную цифру
    jmp .digit_loop                 ; и повторяем
.digits_done:
    test r9, r9                     ; прочитали хотя бы одну цифру?
    jz  .error                      ; нет ("abc", одинокий "-", пусто между запятыми): ошибка
    test r8, r8                     ; число было отрицательным?
    jz  .add                        ; нет: оставляем как есть
    neg rdx                         ; да: меняем знак
.add:
    add rax, rdx                    ; сумма += число
    inc rcx                         ; чисел стало на одно больше
    call skip_ws                    ; пропускаем пробелы после числа
    cmp rsi, rdi                    ; данные кончились?
    jae .ok                         ; да: конец файла без '\n' в конце тоже нормально
    mov r10b, [rsi]                 ; берём разделитель
    inc rsi                         ; сразу съедаем его
    cmp r10b, ','                   ; это запятая?
    je  .next_number                ; да: после неё ждём ещё одно число
    cmp r10b, 10                    ; это конец строки '\n'?
    je  .ok                         ; да: строка разобрана
.error:                             ; сюда падаем и по прыжкам, и если разделитель какой-то другой
    stc                             ; stc: CF = 1 («ошибка»)
    ret
.ok:
    clc                             ; clc: CF = 0 («всё хорошо»)
    ret

; ---------------------------------------------------------------------------
_start:
    cmp qword [rsp], 2              ; argc = имя программы + ровно один аргумент (файл)
    jne .no_args                    ; аргументов не столько, сколько нужно: показываем подсказку

    ; r14 = имя файла, r15 = его длина (нужны для печати в конце)
    mov r14, [rsp + 16]             ; r14 = argv[1], адрес строки с именем файла
    xor r15, r15                    ; r15 = длина имени, пока 0
.name_len:
    cmp byte [r14 + r15], 0         ; текущий байт имени равен 0 (конец строки)?
    je  .name_done                  ; да: длина посчитана
    inc r15                         ; нет: считаем символ
    jmp .name_len                   ; идём дальше
.name_done:

    ; --- fd = open(argv[1], O_RDONLY) ---
    mov rax, 2                      ; номер системного вызова open
    mov rdi, r14                    ; 1-й аргумент: путь к файлу
    xor rsi, rsi                    ; 2-й аргумент: флаги = 0 (O_RDONLY, только чтение)
    xor rdx, rdx                    ; 3-й аргумент: mode = 0 (нужен только при создании)
    syscall                         ; открываем; в rax вернётся fd или отрицательная ошибка
    test rax, rax                   ; смотрим знак результата
    js  .corrupted                  ; отрицательный: файла нет или не открывается
    mov rbx, rax                    ; запоминаем дескриптор файла в rbx

    ; --- r12 = начало буфера = текущий конец кучи: brk(0) ---
    mov rax, 12                     ; номер системного вызова brk
    xor rdi, rdi                    ; аргумент 0 = «просто скажи, где сейчас конец кучи»
    syscall                         ; в rax придёт текущий конец кучи
    mov r12, rax                    ; он и будет началом нашего буфера
    xor r13, r13                    ; прочитано пока 0 байт

.read_loop:
    ; просим ядро расширить кучу до base + total + CHUNK
    lea rdi, [r12 + r13 + CHUNK]    ; считаем нужный конец кучи (lea только считает адрес)
    mov rax, 12                     ; brk
    syscall                         ; brk возвращает новый конец; если вернул меньше - не вышло
    cmp rax, rdi                    ; получили столько, сколько просили?
    jb  .close_corrupted            ; меньше (below): память не дали, ошибка

    ; read(fd, base + total, CHUNK)
    mov rax, 0                      ; номер системного вызова read
    mov rdi, rbx                    ; откуда читаем: наш fd
    lea rsi, [r12 + r13]            ; куда: сразу за уже прочитанным
    mov rdx, CHUNK                  ; сколько максимум
    syscall                         ; в rax вернётся, сколько прочитано
    test rax, rax                   ; смотрим результат
    js  .close_corrupted            ; отрицательный: ошибка чтения (например, это директория)
    jz  .read_done                  ; 0 байт: файл закончился
    add r13, rax                    ; запоминаем, что прочитано ещё rax байт
    jmp .read_loop                  ; и читаем следующий кусок

.read_done:
    mov rax, 3                      ; номер системного вызова close
    mov rdi, rbx                    ; какой fd закрываем
    syscall                         ; закрываем файл: он нам больше не нужен

    ; --- разбор: rsi бежит по данным, rdi = конец ---
    mov rsi, r12                    ; rsi = начало данных
    lea rdi, [r12 + r13]            ; rdi = конец данных (начало + сколько прочитали)

    call parse_line                 ; первая строка (x)
    jc  .corrupted                  ; CF = 1: строка некорректна
    mov rbx, rax                    ; rbx = сумма x
    mov rbp, rcx                    ; rbp = количество чисел в x

    call parse_line                 ; вторая строка (y); rsi уже стоит на её начале
    jc  .corrupted                  ; CF = 1: строка некорректна
    cmp rcx, rbp                    ; количества чисел в строках одинаковые?
    jne .corrupted                  ; нет: файл испорчен
    sub rbx, rax                    ; rbx = Σx - Σy = сумма разностей

    ; после второй строки допускаем только пустое место
.trail:
    cmp rsi, rdi                    ; данные кончились?
    jae .compute                    ; да: лишнего нет, считаем ответ
    mov r10b, [rsi]                 ; берём очередной символ хвоста
    inc rsi                         ; и сразу съедаем его
    cmp r10b, ' '                   ; пробел?
    je  .trail                      ; допустимо, проверяем дальше
    cmp r10b, 9                     ; табуляция?
    je  .trail                      ; допустимо
    cmp r10b, 10                    ; перевод строки?
    je  .trail                      ; допустимо
    cmp r10b, 13                    ; '\r'?
    je  .trail                      ; допустимо
    jmp .corrupted                  ; любой другой символ: лишние данные, файл испорчен

.compute:
    mov rax, rbx                    ; делимое = сумма разностей
    cqo                             ; расширяем знак rax в rdx:rax (нужно для знакового деления)
    idiv rbp                        ; rax = сумма / количество (со знаком, дробная часть отбрасывается)
    mov rbx, rax                    ; запоминаем ответ в rbx (rax испортит print_int)

    ; печатаем "<имя>: <результат>\n"
    mov rsi, r14                    ; адрес имени файла
    mov rdx, r15                    ; его длина
    call write_out                  ; печатаем имя
    mov rsi, sep                    ; адрес ": "
    mov rdx, sep_len                ; длина разделителя
    call write_out                  ; печатаем разделитель
    mov rax, rbx                    ; число для печати в rax
    call print_int                  ; печатаем результат
    mov rsi, nl                     ; адрес перевода строки
    mov rdx, 1                      ; один байт
    call write_out                  ; завершаем строку

    mov rax, 60                     ; номер системного вызова exit
    xor rdi, rdi                    ; код возврата 0 = всё хорошо
    syscall

.close_corrupted:                   ; ошибка, пока файл был открыт: сначала закроем его
    mov rax, 3                      ; close
    mov rdi, rbx                    ; fd лежит в rbx
    syscall                         ; закрываем, дальше падаем в .corrupted

.corrupted:                         ; "<имя>: файл испорчен\n"
    mov rsi, r14                    ; адрес имени файла
    mov rdx, r15                    ; его длина
    call write_out                  ; печатаем имя
    mov rsi, sep                    ; адрес ": "
    mov rdx, sep_len                ; длина разделителя
    call write_out                  ; печатаем разделитель
    mov rsi, bad_msg                ; адрес сообщения «файл испорчен»
    mov rdx, bad_msg_len            ; его длина
    call write_out                  ; печатаем сообщение
    mov rax, 60                     ; exit
    mov rdi, 1                      ; код возврата 1 = ошибка
    syscall

.no_args:                           ; аргументов не один: печатаем подсказку и выходим
    mov rsi, usage                  ; адрес подсказки
    mov rdx, usage_len              ; её длина
    call write_out                  ; печатаем
    mov rax, 60                     ; exit
    mov rdi, 1                      ; код возврата 1 = ошибка
    syscall
